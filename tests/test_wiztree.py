import os
import tempfile
import unittest
from unittest import mock

from dsk import scan, wiztree

CSV = '''Generated by WizTree 4.20 11/20/2026 10:00:00 PM
"File Name","Size","Allocated","Modified","Attributes","Files","Folders"
"C:\\","500000000000","500000000000","2026/11/20 22:00:00",0,100,10
"C:\\Users\\me\\AppData\\Local\\Temp\\","3000000000","3100000000","2026/11/20 22:00:00",16,10,2
"C:\\Users\\me\\AppData\\Local\\Temp\\setup\\","1000000000","1000000000","2026/11/20 22:00:00",16,10,2
"C:\\Users\\me\\Documents\\","9000000000","9000000000","2026/11/20 22:00:00",16,10,2
"C:\\Users\\me\\Documents\\site\\node_modules\\","2000000000","2000000000","2026/01/01 10:00:00",16,10,2
"C:\\Users\\me\\Documents\\site\\node_modules\\x\\node_modules\\","500000000","500000000","2026/01/01 10:00:00",16,10,2
"C:\\Users\\me\\Videos\\","40000000000","40000000000","2026/11/20 22:00:00",16,10,2
"C:\\Users\\me\\Videos\\raw.mov","39000000000","39000000000","2025/02/01 10:00:00",32,0,0
"C:\\pagefile.sys","8000000000","8000000000","2026/11/20 22:00:00",32,0,0
'''


class WizTreeParseTest(unittest.TestCase):
    def test_parse(self):
        home = r"C:\Users\me"
        roots = {"caches": [home + r"\AppData\Local\Temp"], "dev": [], "trash": [], "apps": [],
                 "photos": [], "movies": [home + r"\Videos"], "music": [], "docs": [home + r"\Documents"]}
        fd, path = tempfile.mkstemp(suffix=".csv")
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(CSV)
        r = scan.ScanResult()
        # Parse with Windows path rules on any OS.
        import ntpath
        with mock.patch.object(scan, "roots", return_value=roots), mock.patch.object(scan, "HOME", home), \
                mock.patch.object(wiztree.os, "sep", "\\"), mock.patch.object(wiztree.os, "path", ntpath), \
                mock.patch.object(scan, "norm", lambda p: ntpath.normcase(ntpath.normpath(p))), \
                mock.patch.object(wiztree, "norm", lambda p: ntpath.normcase(ntpath.normpath(p))), \
                mock.patch.object(scan, "_project_mtime", return_value=0):
            rows = wiztree.parse(path, r)
        os.remove(path)
        self.assertEqual(rows, 9)
        self.assertEqual(r.sizes["caches"], 3100000000)
        self.assertEqual(r.sizes["movies"], 40000000000)
        # the outer node_modules moves from Documents to Developer; the nested one isn't double counted
        self.assertEqual(r.sizes["docs"], 7000000000)
        self.assertEqual(r.sizes["dev"], 2000000000)
        self.assertEqual(len(r.dev_folders), 1)
        top = r.largest()
        self.assertEqual(top[0]["path"], r"C:\Users\me\Videos\raw.mov")
        self.assertEqual(top[0]["cat"], "movies")
        self.assertIn(ntpath.normcase(r"C:\Users\me\AppData\Local\Temp\setup"), r.folders)


if __name__ == "__main__":
    unittest.main()
