"""Optional fast scan on Windows with WizTree (https://diskanalyzer.com).

WizTree reads the drive's Master File Table directly, so it measures a whole NTFS
drive in seconds instead of minutes. Dsk runs it with its command line export
and reads the CSV into the same ScanResult the built-in walk produces. WizTree
itself is the user's own install; Dsk doesn't bundle it.
"""

import csv
import heapq
import os
import subprocess
import tempfile
import time

from . import scan
from .scan import DEV_DIRS, KEYS, TOP_FILES, norm

CANDIDATES = [
    os.path.join(os.environ.get("ProgramFiles", r"C:\Program Files"), "WizTree", "WizTree64.exe"),
    os.path.join(os.environ.get("ProgramFiles", r"C:\Program Files"), "WizTree", "WizTree.exe"),
    os.path.join(os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)"), "WizTree", "WizTree.exe"),
    os.path.join(os.environ.get("LOCALAPPDATA", ""), "Programs", "WizTree", "WizTree64.exe"),
]


def find(custom=None):
    for p in ([custom] if custom else []) + CANDIDATES:
        if p and os.path.isfile(p):
            return p
    return None


def export(exe, drive, out_csv, admin=True, timeout=900, progress=None):
    """Runs WizTree's export and waits for the CSV to be complete."""
    args = [exe, drive, "/export=%s" % out_csv, "/admin=%d" % (1 if admin else 0),
            "/exportfiles=1", "/exportfolders=1"]
    try:
        os.remove(out_csv)
    except OSError:
        pass
    p = subprocess.Popen(args, creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
    start = time.time()
    # With /admin=1 WizTree may hand over to an elevated copy and exit early, so wait on the file.
    last, stable = -1, 0
    while time.time() - start < timeout:
        if progress:
            progress()
        time.sleep(0.5)
        if not os.path.exists(out_csv):
            if p.poll() is not None and time.time() - start > 20 and not os.path.exists(out_csv):
                raise OSError("WizTree finished without writing an export (was the admin prompt declined?)")
            continue
        size = os.path.getsize(out_csv)
        stable = stable + 1 if size == last and size > 0 else 0
        last = size
        if stable >= 4 and p.poll() is not None:
            try:
                with open(out_csv, "a"):
                    return out_csv
            except OSError:
                continue
    raise OSError("WizTree took too long")


def parse(path, result, progress=None):
    """Fills a ScanResult from a WizTree CSV export."""
    r = result
    plan = scan.roots()
    owners = {}
    for cat in ("caches", "dev", "trash", "apps", "photos", "movies", "music", "docs"):
        for p in plan.get(cat, []):
            owners.setdefault(norm(p), cat)
    owner_list = sorted(owners.items(), key=lambda kv: -len(kv[0]))
    home = norm(scan.HOME)

    def owner_of(n):
        for root, cat in owner_list:
            if n == root or n.startswith(root + os.sep):
                return root, cat
        return None, None

    dev_found = []
    rows = 0
    with open(path, "r", encoding="utf-8-sig", errors="replace", newline="") as f:
        first = f.readline()
        if "File Name" not in first:
            pass  # "Generated by WizTree..." banner; the header is next
        else:
            f.seek(0)
        reader = csv.DictReader(f)
        for row in reader:
            rows += 1
            if progress and rows % 20000 == 0:
                progress()
            name = row.get("File Name") or ""
            try:
                size = int(row.get("Allocated") or row.get("Size") or 0)
            except ValueError:
                continue
            is_dir = name.endswith("\\")
            full = name.rstrip("\\")
            n = norm(full)
            if is_dir:
                if n in owners:
                    r.sizes[owners[n]] += size
                    r.folders[n] = size
                    continue
                root, cat = owner_of(n)
                if root:
                    depth = n[len(root):].count(os.sep)
                    if depth <= scan.SHALLOW_DEPTH:
                        r.folders[n] = size
                if os.path.basename(full) in DEV_DIRS and n.startswith(home + os.sep):
                    dev_found.append((n, full, size, cat))
                continue
            if size > 50 * 1024 * 1024:
                try:
                    mtime = time.mktime(time.strptime((row.get("Modified") or "")[:19], "%Y/%m/%d %H:%M:%S"))
                except ValueError:
                    mtime = 0
                root, cat = owner_of(n)
                item = (size, full, mtime, mtime, cat or "system")
                if len(r.top) < TOP_FILES:
                    heapq.heappush(r.top, item)
                elif size > r.top[0][0]:
                    heapq.heapreplace(r.top, item)
    # Outermost dev folders only; their bytes move from the category they sit in to Developer.
    dev_found.sort(key=lambda t: len(t[0]))
    kept = []
    for n, full, size, cat in dev_found:
        if any(n.startswith(k + os.sep) for k in kept):
            continue
        kept.append(n)
        r.folders[n] = size
        if cat and cat != "dev":
            r.sizes[cat] = max(0, r.sizes[cat] - size)
            r.sizes["dev"] += size
        try:
            mtime = scan._project_mtime(full)
        except OSError:
            mtime = 0
        r.dev_folders.append({"path": full, "size": size, "mtime": mtime, "kind": os.path.basename(full)})
    return rows


def run(exe, admin=True, progress=None):
    r = scan.ScanResult()
    r.engine = "wiztree"
    drive = scan.disk_root().rstrip("\\")
    r.current = "WizTree is reading " + drive
    out = os.path.join(tempfile.gettempdir(), "dsk-wiztree-%d.csv" % os.getpid())
    tick = (lambda: progress(r)) if progress else None
    export(exe, drive, out, admin=admin, progress=tick)
    r.current = "Reading WizTree's results"
    parse(out, r, progress=tick)
    try:
        os.remove(out)
    except OSError:
        pass
    try:
        from . import winshell
        r.sizes["trash"], r.counts["trash"] = winshell.recycle_bin_size()
    except Exception:
        pass
    r.finish()
    if progress:
        progress(r)
    return r


__all__ = ["find", "run", "parse", "KEYS"]
